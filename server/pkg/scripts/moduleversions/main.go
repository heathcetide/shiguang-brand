// Command moduleversions regenerates lingcli's module catalog from go.mod files
// and stable Git tags. A new module path starts at v0.1.0; tags belonging to an
// old path are deliberately not inherited after a directory move.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const moduleRoot = "github.com/LingByte/ling-base"
const firstVersion = "v0.1.0"

var stableVersion = regexp.MustCompile(`^v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$`)

func main() {
	root := flag.String("root", ".", "repository root")
	check := flag.Bool("check", false, "check the catalog without writing it")
	requireTags := flag.Bool("require-tags", false, "refuse a CLI release until every library has a stable tag")
	flag.Parse()
	if err := run(*root, *check, *requireTags); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(root string, check, requireTags bool) error {
	cmd := exec.Command("git", "tag", "--list")
	cmd.Dir = root
	out, err := cmd.Output()
	if err != nil {
		return fmt.Errorf("list module tags: %w", err)
	}
	content, err := generateWithPolicy(root, strings.Fields(string(out)), requireTags)
	if err != nil {
		return err
	}
	path := filepath.Join(root, "lingcli", "module_versions.go")
	if check {
		current, err := os.ReadFile(path)
		if err != nil || !bytes.Equal(current, content) {
			return fmt.Errorf("lingcli/module_versions.go is out of date; run make sync-cli-versions and commit the result before releasing lingcli")
		}
		return nil
	}
	return os.WriteFile(path, content, 0644)
}

func generate(root string, tags []string) ([]byte, error) {
	return generateWithPolicy(root, tags, false)
}

func generateWithPolicy(root string, tags []string, requireTags bool) ([]byte, error) {
	latest := make(map[string]string)
	for _, tag := range tags {
		dir, version := ".", tag
		if i := strings.LastIndexByte(tag, '/'); i >= 0 {
			dir, version = tag[:i], tag[i+1:]
		}
		if !stableVersion.MatchString(version) {
			continue
		}
		if previous := latest[dir]; previous == "" || newer(version, previous) {
			latest[dir] = version
		}
	}

	versions := make(map[string]string)
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			if path != root && (strings.HasPrefix(entry.Name(), ".") || entry.Name() == "vendor" || entry.Name() == "node_modules" || entry.Name() == "embed_source") {
				return filepath.SkipDir
			}
			return nil
		}
		if entry.Name() != "go.mod" {
			return nil
		}
		dir, err := filepath.Rel(root, filepath.Dir(path))
		if err != nil {
			return err
		}
		dir = filepath.ToSlash(dir)
		// The CLI is not a library dependency. Including its own tag would
		// make every CLI release invalidate the catalog it was built from.
		if dir == "lingcli" {
			return nil
		}
		content, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		module := ""
		for _, line := range strings.Split(string(content), "\n") {
			fields := strings.Fields(line)
			if len(fields) >= 2 && fields[0] == "module" {
				module = strings.Trim(fields[1], `"`)
				break
			}
		}
		want := moduleRoot
		if dir != "." {
			want += "/" + dir
		}
		if module != want {
			return fmt.Errorf("%s: module path %q does not match directory (want %q)", path, module, want)
		}
		version := latest[dir]
		if version == "" {
			if requireTags {
				prefix := ""
				if dir != "." {
					prefix = dir + "/"
				}
				return fmt.Errorf("library %s has no stable tag; publish %sv0.1.0 before releasing lingcli", module, prefix)
			}
			version = firstVersion
		}
		versions[module] = version
		return nil
	})
	if err != nil {
		return nil, err
	}

	keys := make([]string, 0, len(versions))
	for module := range versions {
		keys = append(keys, module)
	}
	sort.Strings(keys)
	var out strings.Builder
	out.WriteString("// Code generated by go run ./scripts/moduleversions; DO NOT EDIT.\n\npackage main\n\n")
	out.WriteString("// New module paths use v0.1.0 for their first release. Publish library tags\n// before releasing a CLI that depends on them.\nvar lingBaseSubmoduleVersions = map[string]string{\n")
	for _, module := range keys {
		fmt.Fprintf(&out, "%q: %q,\n", module, versions[module])
	}
	out.WriteString("}\n")
	return format.Source([]byte(out.String()))
}

// Compare decimal components by length first, avoiding integer overflow.
func newer(a, b string) bool {
	left := strings.Split(strings.TrimPrefix(a, "v"), ".")
	right := strings.Split(strings.TrimPrefix(b, "v"), ".")
	for i := range left {
		if len(left[i]) != len(right[i]) {
			return len(left[i]) > len(right[i])
		}
		if left[i] != right[i] {
			return left[i] > right[i]
		}
	}
	return false
}
