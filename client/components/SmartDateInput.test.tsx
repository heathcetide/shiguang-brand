import React from "react";
import renderer, { act } from "react-test-renderer";
import { Keyboard, Platform, StyleSheet, Text, TouchableOpacity } from "react-native";
import DateTimePicker from "@react-native-community/datetimepicker";
import { SmartDateInput } from "./SmartDateInput";
let mockTheme = "light";
jest.mock("@/hooks/useAppThemeColors", () => ({ useAppThemeColors: () => ({ ink: "ink", surface: "surface", critical: "critical" }) }));
jest.mock("@/contexts/ThemeContext", () => ({ useThemePreference: () => ({ resolvedTheme: mockTheme }) }));
jest.mock("@/components/ThemedFontAwesome6", () => () => null);
jest.mock("@react-native-community/datetimepicker", () => () => null);
let tree: renderer.ReactTestRenderer;
beforeEach(() => { jest.replaceProperty(Platform, "OS", "android"); jest.spyOn(Keyboard, "dismiss").mockImplementation(() => undefined); });
afterEach(() => { act(() => tree.unmount()); jest.restoreAllMocks(); });
const open = () => act(() => tree.root.findByType(TouchableOpacity).props.onPress());
it.each(["light", "dark"])("keeps %s native time theme, cancellation, repeat opens and stale callbacks safe", (theme) => {
  mockTheme = theme; const changed = jest.fn();
  act(() => { tree = renderer.create(<SmartDateInput label="早餐" mode="time" value="08:30" onChange={changed} />); });
  open(); open(); expect(Keyboard.dismiss).toHaveBeenCalledTimes(1);
  const first = tree.root.findByType(DateTimePicker).props;
  expect(first.themeVariant).toBe(theme); expect(first.is24Hour).toBe(true);
  expect(first.value.getHours()).toBe(8); expect(first.value.getMinutes()).toBe(30);
  act(() => first.onChange({ type: "dismissed" }));
  expect(changed).not.toHaveBeenCalled(); expect(tree.root.findAllByType(DateTimePicker)).toHaveLength(0);
  open(); act(() => first.onChange({ type: "set" }, new Date(2026, 9, 25, 9, 0)));
  expect(changed).not.toHaveBeenCalled();
  const current = tree.root.findByType(DateTimePicker).props;
  act(() => { current.onChange({ type: "set" }, new Date(2026, 9, 25, 10, 45)); current.onChange({ type: "set" }, new Date(2026, 9, 25, 11, 0)); });
  expect(changed.mock.calls).toEqual([["10:45"]]);
  act(() => tree.update(<SmartDateInput label="早餐" mode="time" value="10:45" onChange={changed} />));
  open(); expect(tree.root.findByType(DateTimePicker).props.value.getHours()).toBe(10);
});
it("leaves unknown dates untouched and blocks disabled or unmounted callbacks", () => {
  const changed = jest.fn();
  act(() => { tree = renderer.create(<SmartDateInput label="到期日期" value="" onChange={changed} />); });
  open(); const callback = tree.root.findByType(DateTimePicker).props.onChange;
  act(() => tree.update(<SmartDateInput label="到期日期" value="" disabled onChange={changed} />));
  act(() => callback({ type: "set" }, new Date()));
  open(); expect(tree.root.findAllByType(DateTimePicker)).toHaveLength(0);
  act(() => tree.unmount()); act(() => callback({ type: "set" }, new Date()));
  expect(changed).not.toHaveBeenCalled();
});
it("allows containers, labels and values to grow for large text", () => {
  act(() => { tree = renderer.create(<SmartDateInput label="到期日期（建议）" value="2026-11-01" onChange={jest.fn()} />); });
  const button = tree.root.findByType(TouchableOpacity);
  expect(StyleSheet.flatten(button.props.style)).toMatchObject({ minHeight: 52, paddingVertical: 12 });
  expect(StyleSheet.flatten(button.props.style).height).toBeUndefined();
  expect(tree.root.findAllByType(Text).every(text => text.props.numberOfLines === undefined)).toBe(true);
  expect(button.props.accessibilityLabel).toBe("到期日期（建议）");
});
it("accepts valid HH:mm web values, clear/error recovery, theme and labels", () => {
  jest.replaceProperty(Platform, "OS", "web"); mockTheme = "dark";
  const changed = jest.fn();
  act(() => { tree = renderer.create(<SmartDateInput label="早餐" mode="time" value="25:00" error="时间无效" onChange={changed} />); });
  let input = tree.root.findByType("input");
  expect(input.props.value).toBe(""); expect(input.props["aria-invalid"]).toBe(true);
  expect(input.props["aria-label"]).toBe("早餐"); expect(input.props.style.colorScheme).toBe("dark");
  for (const value of ["24:00", "12:60", "garbage"]) act(() => input.props.onChange({ target: { value } }));
  expect(changed).not.toHaveBeenCalled();
  for (const value of ["00:00", "23:59", ""]) act(() => input.props.onChange({ target: { value } }));
  expect(changed.mock.calls).toEqual([["00:00"], ["23:59"], [""]]);
  act(() => tree.update(<SmartDateInput label="早餐" mode="time" value="23:59" onChange={changed} />));
  input = tree.root.findByType("input"); expect(input.props.value).toBe("23:59"); expect(input.props["aria-invalid"]).toBe(false);
});
it("preserves calendar date formatting for inventory and other existing date callers", () => {
  const changed = jest.fn();
  act(() => { tree = renderer.create(<SmartDateInput value="2026-11-01" onChange={changed} />); });
  open();
  act(() => tree.root.findByType(DateTimePicker).props.onChange({ type: "set" }, new Date(2026, 10, 2, 23, 45)));
  expect(changed).toHaveBeenCalledWith("2026-11-02");
});
